import json
import logging
import time

from django.conf import settings
from django.core.exceptions import RequestDataTooBig
from django.db import DatabaseError
from django.http import HttpResponse, JsonResponse
from django.views.decorators.http import require_GET, require_POST

from . import services
from .auth import supabase_user_required
from .models import Report
from .validators import (ValidationError, clean_text, decode_screenshot, validate_capture_meta,
                         validate_coordinates, validate_report_request)

logger = logging.getLogger(__name__)


def _error(message, status, code=None, **extra):
    body = {'success': False, 'error': message, **extra}
    if code:
        body['code'] = code
    return JsonResponse(body, status=status)


def _owned_report(request, report_id):
    """Look up by id *and* owner, so another user's id is indistinguishable from a missing one."""
    return Report.objects.filter(id=report_id, owner_id=request.report_owner_id).first()


@require_POST
@supabase_user_required
def generate_report(request):
    """
    Start a report for the selected location. Body:
      {location: {name, latitude, longitude}, radius_m, business_type?, source?,
       heatmap: {image?, capture_error?, analysed_lat, analysed_lon, center_lat, center_lon, zoom,
                 sector_counts, captured_at}}
    Analysis data is recomputed on the server; nothing numeric is taken from the client
    except the coordinates used to check the screenshot belongs to this location.
    """
    try:
        data = json.loads(request.body or b'{}')
    except RequestDataTooBig:
        return _error('The heatmap screenshot is too large.', 413, 'image_too_large')
    except (json.JSONDecodeError, UnicodeDecodeError):
        return _error('Invalid JSON', 400, 'invalid_json')

    try:
        cleaned = validate_report_request(data)
        capture = validate_capture_meta(cleaned['heatmap'], cleaned['latitude'], cleaned['longitude'])
        screenshot = None
        if cleaned['heatmap'].get('image'):
            screenshot, size = decode_screenshot(cleaned['heatmap']['image'], settings.REPORT_SCREENSHOT_MAX_BYTES)
            capture['width'], capture['height'] = size
        captured_at = cleaned['heatmap'].get('captured_at')
        now_ms = time.time() * 1000
        if (screenshot and isinstance(captured_at, (int, float)) and not isinstance(captured_at, bool)
                and now_ms - 3_600_000 <= captured_at <= now_ms + 300_000):
            capture['captured_at_ms'] = int(captured_at)
    except ValidationError as exc:
        status = {'image_too_large': 413, 'heatmap_mismatch': 409}.get(exc.code, 400)
        return _error(str(exc), status, exc.code)

    try:
        report = services.create_report(request.report_owner_id, cleaned, screenshot, capture)
    except services.ReportLimitError as exc:
        extra = {}
        if exc.existing is not None:
            extra['report_id'] = str(exc.existing.id)
            extra['status_url'] = f'/api/reports/{exc.existing.id}/status/'
        return _error(str(exc), exc.status, 'busy' if exc.status == 409 else 'rate_limited', **extra)

    report.refresh_from_db()
    payload = services.status_payload(report)
    payload['status_url'] = f'/api/reports/{report.id}/status/'
    return JsonResponse(payload, status=202)


@require_GET
@supabase_user_required
def report_status(request, report_id):
    report = _owned_report(request, report_id)
    if report is None:
        return _error('Report not found', 404, 'not_found')
    return JsonResponse(services.status_payload(report))


@require_GET
@supabase_user_required
def download_report(request, report_id):
    report = _owned_report(request, report_id)
    if report is None:
        return _error('Report not found', 404, 'not_found')
    if report.status != Report.SUCCEEDED or not report.pdf:
        return _error('Report is not ready', 409, 'not_ready')
    filename = f'business-report-{report.created_at:%Y%m%d-%H%M}.pdf'
    response = HttpResponse(bytes(report.pdf), content_type='application/pdf')
    response['Content-Disposition'] = f'attachment; filename="{filename}"'
    response['Cache-Control'] = 'no-store, private'
    response['X-Content-Type-Options'] = 'nosniff'
    return response


@require_GET
@supabase_user_required
def list_reports(request):
    """Return all reports generated by the authenticated user so they appear in Favorites."""
    try:
        reports = list(Report.objects.filter(owner_id=request.report_owner_id).order_by('-created_at')[:50])
    except DatabaseError:
        # Typically the report table does not exist yet (migrations not applied).
        logger.exception('Report list query failed')
        return _error('Saved reports are unavailable: the server database is not set up '
                      '(run "python manage.py migrate").', 503, 'db_unavailable')
    items = []
    for r in reports:
        items.append({
            'id': str(r.id),
            'kind': r.kind,
            'location_name': r.location_name,
            'latitude': r.latitude,
            'longitude': r.longitude,
            'radius_m': r.radius_m,
            'status': r.status,
            'page_count': r.page_count,
            'ai_used': r.ai_used,
            'created_at': r.created_at.strftime('%b %d, %Y %I:%M %p') if r.created_at else None,
            'created_at_iso': r.created_at.isoformat() if r.created_at else None,
            'has_pdf': bool(r.status == Report.SUCCEEDED and r.pdf),
            'download_url': f'/api/reports/{r.id}/download/' if (r.status == Report.SUCCEEDED and r.pdf) else None,
        })
    return JsonResponse({'success': True, 'reports': items})


@require_POST
@supabase_user_required
def generate_favorites_report(request):
    """
    Queue a full-detail PDF comparing the user's saved favorites.
    Body (optional): {"ids": [favorite ids]} – the places ticked on /favorites/;
    without it the most recent favorites are used (up to MAX_PLACES).
    The favorites are read from Supabase with the caller's own token (RLS).
    """
    from favorites import store
    from .favorites_report import MAX_PLACES

    try:
        data = json.loads(request.body or b'{}')
    except (json.JSONDecodeError, UnicodeDecodeError):
        return _error('Invalid JSON', 400, 'invalid_json')
    ids = data.get('ids') if isinstance(data, dict) else None
    if ids is not None and (not isinstance(ids, list) or not all(isinstance(i, int) for i in ids)):
        return _error('ids must be a list of favorite ids', 400, 'invalid_ids')

    token = request.META['HTTP_AUTHORIZATION'][7:].strip()
    try:
        favorites = store.list_favorites(token)
    except store.StoreError as exc:
        if exc.status in (401, 403):
            return _error('Invalid or expired session. Please sign in again.', 401, 'auth')
        if exc.status == 404 or exc.code in ('PGRST202', '42P01'):
            return _error('Favorites table missing: run supabase/favorites.sql in Supabase.', 503, 'favorites_missing')
        return _error('Your favorites could not be loaded right now. Please try again.', 502, 'favorites_unavailable')

    if ids:
        wanted = set(ids)
        favorites = [f for f in favorites if f.get('id') in wanted]
    if not favorites:
        return _error('No saved places to export. Save places with the heart icon first.', 400, 'no_favorites')
    if ids and len(favorites) > MAX_PLACES:
        return _error(f'Select at most {MAX_PLACES} places for one report.', 400, 'too_many')
    favorites = favorites[:MAX_PLACES]

    places = []
    for f in favorites:
        try:
            lat, lon = validate_coordinates(f.get('latitude'), f.get('longitude'))
        except ValidationError:
            continue
        places.append({'id': f.get('id'), 'name': clean_text(f.get('name'), 200) or 'Saved place',
                       'category': clean_text(f.get('category'), 60), 'address': clean_text(f.get('address'), 255),
                       'latitude': lat, 'longitude': lon, 'potential_score': f.get('potential_score')})
    if not places:
        return _error('None of the selected favorites has valid coordinates.', 400, 'no_favorites')

    request_data = {
        'name': f'Favorites comparison ({len(places)} place{"s" if len(places) != 1 else ""})',
        'address': '', 'latitude': places[0]['latitude'], 'longitude': places[0]['longitude'],
        'radius_m': 5000, 'business_type': '', 'source': 'dashboard',
    }
    try:
        report = services.create_report(request.report_owner_id, request_data, None, {}, kind=Report.FAVORITES, places=places)
    except services.ReportLimitError as exc:
        extra = {'report_id': str(exc.existing.id)} if exc.existing is not None else {}
        return _error(str(exc), exc.status, 'busy' if exc.status == 409 else 'rate_limited', **extra)
    except DatabaseError:
        logger.exception('Could not store favorites report')
        return _error('Reports cannot be stored: the server database is not set up (run "python manage.py migrate").',
                      503, 'db_unavailable')
    report.refresh_from_db()
    payload = services.status_payload(report)
    payload['status_url'] = f'/api/reports/{report.id}/status/'
    return JsonResponse(payload, status=202)
